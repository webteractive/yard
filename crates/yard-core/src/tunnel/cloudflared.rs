//! cloudflared, the first tunnel provider (tunnels spec §7): its config files and where
//! its certificates and credentials live. Yard names these paths; it never reads the files.

use std::path::{Path, PathBuf};

/// The two loopback ports of a tunnel: nginx's listener (the origin) and cloudflared's
/// metrics server, which answers `/ready` and `/quicktunnel`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Origin {
    pub origin_port: u16,
    pub metrics_port: u16,
}

/// Where `yard tunnels domain add` has cloudflared sign in for `domain`: cloudflared's `HOME`
/// during `tunnel login`, so each domain gets a certificate of its own.
pub fn cert_dir(home: &Path, domain: &str) -> PathBuf {
    home.join(".cloudflared/yard").join(domain)
}

/// The certificate `tunnel login` writes under [`cert_dir`]; management commands get it as
/// `--origincert`.
pub fn cert_path(home: &Path, domain: &str) -> PathBuf {
    cert_dir(home, domain).join(".cloudflared/cert.pem")
}

/// The credentials file of a tunnel Yard creates (`tunnel create --credentials-file`).
pub fn created_credentials(home: &Path, domain: &str, name: &str) -> PathBuf {
    cert_dir(home, domain).join(format!("{name}.json"))
}

/// cloudflared's own credentials path for a tunnel Yard adopts.
pub fn default_credentials(home: &Path, id: &str) -> PathBuf {
    home.join(".cloudflared").join(format!("{id}.json"))
}

/// The target of the DNS record `route dns` makes for a tunnel.
pub fn target(id: &str) -> String {
    format!("{id}.cfargotunnel.com")
}

/// Settings every config has: no self-update (brew owns the binary), `info` logging (at
/// `debug` cloudflared logs request headers, cookies included) and a grace period inside
/// Yard's 5 s stop timeout.
fn fixed(metrics_port: u16) -> String {
    format!("metrics: 127.0.0.1:{metrics_port}\nno-autoupdate: true\nloglevel: info\ngrace-period: 3s\n")
}

fn header() -> String {
    crate::render::header(Path::new("sites.toml"))
}

/// A quick tunnel: `url` makes it one, with a random trycloudflare.com hostname.
pub fn quick_yml(o: Origin) -> String {
    format!("{}url: http://127.0.0.1:{}\n{}", header(), o.origin_port, fixed(o.metrics_port))
}

/// A named tunnel serving `host` only; any other hostname pointed at it gets a 404.
pub fn named_yml(o: Origin, id: &str, credentials: &Path, host: &str) -> String {
    // A JSON string is a valid YAML double-quoted scalar.
    let credentials = serde_json::to_string(&credentials.to_string_lossy()).unwrap_or_default();
    format!(
        "{}tunnel: {id}\ncredentials-file: {credentials}\n{}ingress:\n  - hostname: {host}\n    service: http://127.0.0.1:{}\n  - service: http_status:404\n",
        header(),
        fixed(o.metrics_port),
        o.origin_port
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn quick_yml_is_url_metrics_and_fixed_settings() {
        let o = Origin { origin_port: 33013, metrics_port: 33014 };
        assert_eq!(
            quick_yml(o),
            "# Generated by Yard — edit sites.toml instead\nurl: http://127.0.0.1:33013\nmetrics: 127.0.0.1:33014\nno-autoupdate: true\nloglevel: info\ngrace-period: 3s\n"
        );
    }

    #[test]
    fn named_yml_routes_one_host_and_404s_the_rest() {
        let o = Origin { origin_port: 33011, metrics_port: 33012 };
        let y = named_yml(
            o,
            "1b2c",
            Path::new("/h/.cloudflared/yard/example.com/yard-blog.json"),
            "blog.example.com",
        );
        assert_eq!(
            y,
            "# Generated by Yard — edit sites.toml instead\ntunnel: 1b2c\ncredentials-file: \"/h/.cloudflared/yard/example.com/yard-blog.json\"\nmetrics: 127.0.0.1:33012\nno-autoupdate: true\nloglevel: info\ngrace-period: 3s\ningress:\n  - hostname: blog.example.com\n    service: http://127.0.0.1:33011\n  - service: http_status:404\n"
        );
    }
}
