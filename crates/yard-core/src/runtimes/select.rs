//! Which version a runtime's rules choose and what is installed (runtimes spec §6, §9.2):
//! the `[[default]]` and `[[requires]]` rules, the generated `.yard-install.toml`, and
//! getcomposer.org's index.

use super::recipe::RuntimeRecipe;
use super::version::{RuntimeVersion, VersionSpec};
use crate::{Paths, PhpVersion};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::path::Path;

/// `.yard-install.toml`: what an install checked, written by yardd into the version's root.
/// A version directory without one that names it is not installed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InstallRecord {
    pub version: RuntimeVersion,
    pub url: String,
    pub sha256: String,
    /// The PHP the version needs (`[[requires]]` when it was installed).
    pub requires_php: Option<RuntimeVersion>,
    /// RFC 3339, UTC.
    pub installed_at: String,
}

const RECORD_HEADER: &str = "# Generated by Yard — do not edit. Removed with yard runtime uninstall.\n";

#[derive(Deserialize)]
struct RawRecord {
    version: String,
    url: String,
    sha256: String,
    requires_php: Option<String>,
    installed_at: String,
}

impl InstallRecord {
    pub fn render(&self) -> String {
        let quote = |s: &str| toml_edit::Value::from(s).to_string();
        let mut out = format!(
            "{RECORD_HEADER}version = {}\nurl = {}\nsha256 = {}\n",
            quote(&self.version.to_string()),
            quote(&self.url),
            quote(&self.sha256)
        );
        if let Some(php) = &self.requires_php {
            out.push_str(&format!("requires_php = {}\n", quote(&php.to_string())));
        }
        out.push_str(&format!("installed_at = {}\n", quote(&self.installed_at)));
        out
    }

    pub fn parse(text: &str) -> Option<InstallRecord> {
        let raw: RawRecord = toml::from_str(text).ok()?;
        Some(InstallRecord {
            version: raw.version.parse().ok()?,
            url: raw.url,
            sha256: raw.sha256,
            requires_php: match raw.requires_php {
                Some(p) => Some(p.parse().ok()?),
                None => None,
            },
            installed_at: raw.installed_at,
        })
    }
}

/// The installed versions of runtime `key`, oldest first: each directory of
/// `installs/<key>/` named as a version whose `.yard-install.toml` parses and names that
/// version. A stage, a hand-made directory or a half-deleted one is not installed, so a
/// shim never runs a program Yard did not check. `list` gives a directory's entry names
/// (none when it is missing); `read` a file's text.
pub fn installed(
    paths: &Paths,
    key: &str,
    list: &dyn Fn(&Path) -> Vec<String>,
    read: &dyn Fn(&Path) -> Option<String>,
) -> Vec<(RuntimeVersion, InstallRecord)> {
    let mut out: Vec<_> = list(&paths.installs_dir().join(key))
        .into_iter()
        .filter(|name| !name.starts_with('.'))
        .filter_map(|name| {
            let version: RuntimeVersion = name.parse().ok()?;
            let record = InstallRecord::parse(&read(&paths.install_record(key, &name))?)?;
            (record.version.to_string() == version.to_string()).then_some((version, record))
        })
        .collect();
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

/// The spec a runtime runs where nothing pins it: the first `[[default]]` rule that
/// applies, and the specs it never matches. A rule with `php_below` applies under a PHP
/// below it, and never when `php_full` is `None`. No rules: `None` (the newest installed).
pub fn default_spec(
    recipe: &RuntimeRecipe,
    php_full: Option<&RuntimeVersion>,
) -> Option<(VersionSpec, Vec<VersionSpec>)> {
    recipe
        .defaults
        .iter()
        .find(|rule| match (&rule.php_below, php_full) {
            (None, _) => true,
            (Some(below), Some(php)) => php < below,
            (Some(_), None) => false,
        })
        .map(|rule| (rule.spec.clone(), rule.exclude.clone()))
}

/// The PHP version `v` needs: the `php` of the last `[[requires]]` rule from or before it.
pub fn requires_php(recipe: &RuntimeRecipe, v: &RuntimeVersion) -> Option<RuntimeVersion> {
    recipe.requires.iter().filter(|r| r.from <= *v).max_by(|a, b| a.from.cmp(&b.from)).map(|r| r.php.clone())
}

/// A PHP's full version (`7.2.34`, from its keg), or `<major>.<minor>.0` when it cannot be
/// read, which errs towards the older Composer that runs everywhere on that line.
pub fn php_full_or_zero(full: Option<&str>, v: PhpVersion) -> RuntimeVersion {
    full.and_then(|f| f.parse::<RuntimeVersion>().ok())
        .filter(|f| f.0.len() >= 2)
        .unwrap_or_else(|| RuntimeVersion(vec![u32::from(v.major), u32::from(v.minor), 0]))
}

#[derive(Deserialize)]
struct IndexEntry {
    version: String,
}

/// The channels of getcomposer.org's `versions` index (`1`, `2`, `2.2`), each to its
/// newest release.
pub fn composer_channels(json: &str) -> Result<BTreeMap<String, RuntimeVersion>, String> {
    let index: BTreeMap<String, serde_json::Value> =
        serde_json::from_str(json).map_err(|e| format!("the Composer index is not JSON Yard reads: {e}"))?;
    let mut out = BTreeMap::new();
    for channel in ["1", "2", "2.2"] {
        let Some(list) = index.get(channel) else { continue };
        let entries: Vec<IndexEntry> = serde_json::from_value(list.clone())
            .map_err(|e| format!("the Composer index's {channel:?} is not a list of versions: {e}"))?;
        if let Some(newest) = entries.iter().filter_map(|e| e.version.parse::<RuntimeVersion>().ok()).max() {
            out.insert(channel.to_string(), newest);
        }
    }
    if out.is_empty() {
        return Err("the Composer index lists no channel Yard knows".into());
    }
    Ok(out)
}

/// The version an index install takes for `spec` (runtimes spec §6.2): an exact version is
/// itself; a channel (`2`, `2.2`, `1`) is its newest release; any other major.minor is
/// refused. `Ok(None)`: the index lacks that channel, and the caller uses `[versions]`.
pub fn index_version(
    spec: &VersionSpec,
    channels: &BTreeMap<String, RuntimeVersion>,
) -> Result<Option<RuntimeVersion>, String> {
    if spec.is_exact() {
        return Ok(Some(RuntimeVersion(spec.parts.clone())));
    }
    let name = spec.to_string();
    if ["1", "2", "2.2"].contains(&name.as_str()) {
        return Ok(channels.get(&name).cloned());
    }
    Err(format!("Composer {name} is not a channel; name an exact version, such as 2.7.7"))
}

/// The getcomposer.org channel a release belongs to: `2.2` for the 2.2 LTS, else its major.
pub fn composer_channel(v: &RuntimeVersion) -> String {
    match v.0.as_slice() {
        [2, 2, ..] => "2.2".to_string(),
        [major, ..] => major.to_string(),
        [] => String::new(),
    }
}

/// The hash in a `.sha256sum` file (`<hash>  composer.phar`), lower-cased.
pub fn parse_sha256sum(text: &str) -> Result<String, String> {
    let hash = text.split_whitespace().next().unwrap_or_default();
    if hash.len() == 64 && hash.bytes().all(|b| b.is_ascii_hexdigit()) {
        Ok(hash.to_ascii_lowercase())
    } else {
        Err("the checksum file does not start with a SHA-256".into())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::runtimes::Runtimes;
    use std::collections::BTreeMap;
    use std::path::{Path, PathBuf};

    fn v(s: &str) -> RuntimeVersion {
        s.parse().unwrap()
    }

    fn spec(s: &str) -> VersionSpec {
        VersionSpec::parse(s).unwrap()
    }

    fn composer() -> RuntimeRecipe {
        Runtimes::carried().get("composer").unwrap().recipe().clone()
    }

    const INDEX: &str = include_str!("testdata/composer-versions.json");

    #[test]
    fn php_below_compares_the_full_version() {
        let r = composer();
        assert_eq!(default_spec(&r, Some(&v("7.2.4"))), Some((spec("2.2"), vec![])));
        assert_eq!(default_spec(&r, Some(&v("7.2.5"))), Some((spec("2"), vec![spec("2.2")])));
        assert_eq!(default_spec(&r, Some(&v("7.1.33"))), Some((spec("2.2"), vec![])));
        assert_eq!(default_spec(&r, Some(&v("8.4.27"))), Some((spec("2"), vec![spec("2.2")])));
        // Without a PHP, rules naming php_below are skipped.
        assert_eq!(default_spec(&r, None), Some((spec("2"), vec![spec("2.2")])));
    }

    #[test]
    fn an_unreadable_full_version_counts_as_patch_zero() {
        let php = php_full_or_zero(None, "7.2".parse().unwrap());
        assert_eq!(php, v("7.2.0"));
        assert_eq!(default_spec(&composer(), Some(&php)), Some((spec("2.2"), vec![])));
        assert_eq!(php_full_or_zero(Some("8.4.27"), "8.4".parse().unwrap()), v("8.4.27"));
        assert_eq!(php_full_or_zero(Some("garbage"), "8.4".parse().unwrap()), v("8.4.0"));
    }

    #[test]
    fn requires_follow_from() {
        let r = composer();
        assert_eq!(requires_php(&r, &v("2.2.32")), None);
        assert_eq!(requires_php(&r, &v("2.3.0")), Some(v("7.2.5")));
        assert_eq!(requires_php(&r, &v("2.11.2")), Some(v("7.2.5")));
    }

    fn record(version: &str) -> InstallRecord {
        InstallRecord {
            version: v(version),
            url: format!("https://getcomposer.org/download/{version}/composer.phar"),
            sha256: "a".repeat(64),
            requires_php: None,
            installed_at: "2026-11-19T00:00:00Z".into(),
        }
    }

    #[test]
    fn a_version_without_its_record_is_not_installed() {
        let paths = Paths::new("/r");
        let dir = paths.installs_dir().join("composer");
        let files: BTreeMap<PathBuf, String> = BTreeMap::from([
            (paths.install_record("composer", "2.2.32"), record("2.2.32").render()),
            (paths.install_record("composer", "2.10.0"), record("2.9.0").render()),
            (paths.install_record("composer", "junk"), record("2.2.32").render()),
        ]);
        let list = |d: &Path| {
            assert_eq!(d, dir);
            ["2.2.32", "2.11.2", "2.10.0", ".stage-1-0", "junk"].map(String::from).to_vec()
        };
        let read = |p: &Path| files.get(p).cloned();
        let got = installed(&paths, "composer", &list, &read);
        assert_eq!(got.len(), 1);
        assert_eq!(got[0].0, v("2.2.32"));
    }

    #[test]
    fn install_records_round_trip() {
        let mut r = record("2.11.2");
        r.requires_php = Some(v("7.2.5"));
        let text = r.render();
        assert!(text.starts_with("# Generated by Yard"), "{text}");
        assert_eq!(InstallRecord::parse(&text), Some(r));
        assert_eq!(InstallRecord::parse("version = 3\n"), None);
    }

    #[test]
    fn composer_channels_read_the_saved_index() {
        let c = composer_channels(INDEX).unwrap();
        assert_eq!(c["2"], v("2.11.2"));
        assert_eq!(c["2.2"], v("2.2.32"));
        assert_eq!(c["1"], v("1.10.28"));
        assert!(composer_channels("<html>").is_err());
    }

    #[test]
    fn index_versions_follow_the_spec_rules() {
        let c = composer_channels(INDEX).unwrap();
        assert_eq!(index_version(&spec("2"), &c), Ok(Some(v("2.11.2"))));
        assert_eq!(index_version(&spec("2.2"), &c), Ok(Some(v("2.2.32"))));
        assert_eq!(index_version(&spec("2.7.7"), &c), Ok(Some(v("2.7.7"))));
        assert!(index_version(&spec("2.7"), &c).unwrap_err().contains("exact"));
        let mut without = c.clone();
        without.remove("2.2");
        assert_eq!(index_version(&spec("2.2"), &without), Ok(None));
    }

    #[test]
    fn a_garbled_sha256sum_is_refused() {
        let hash = "241a3d13b7c6d35d970b1f69a000298b66943541302148a438a932f5dd44a9fc";
        assert_eq!(parse_sha256sum(&format!("{hash}  composer.phar\n")), Ok(hash.to_string()));
        assert_eq!(parse_sha256sum(&format!("{}  composer.phar", hash.to_uppercase())), Ok(hash.to_string()));
        assert!(parse_sha256sum("abc  composer.phar").is_err());
        assert!(parse_sha256sum("").is_err());
        assert!(parse_sha256sum(&format!("{hash}x  composer.phar")).is_err());
    }
}
